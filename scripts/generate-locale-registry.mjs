import { readdir, mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const projectRoot = join(root, '..');
const localeDir = join(projectRoot, 'node_modules/@faker-js/faker/dist/locale');
const generatedFile = join(projectRoot, 'src/generated/locale-loaders.ts');

const entries = (await readdir(localeDir, { withFileTypes: true }))
  .filter((entry) => entry.isFile() && entry.name.endsWith('.js') && !entry.name.endsWith('.map'))
  .map((entry) => entry.name.replace(/\.js$/, ''))
  .filter((code) => code !== 'base')
  .sort((a, b) => a.localeCompare(b));

if (!entries.length) {
  throw new Error(`No Faker locales found in ${localeDir}`);
}

const lines = [
  '// Generated by scripts/generate-locale-registry.mjs. Do not edit by hand.',
  "export type FakerLocaleModule = { faker?: unknown; default?: unknown };",
  'export const localeLoaders: Record<string, () => Promise<FakerLocaleModule>> = {',
  ...entries.map((code) => `  ${JSON.stringify(code)}: () => import(${JSON.stringify(`@faker-js/faker/locale/${code}`)}),`),
  '};',
  `export const availableLocaleCodes = ${JSON.stringify(entries)} as const;`,
  '',
];

await mkdir(dirname(generatedFile), { recursive: true });
await writeFile(generatedFile, lines.join('\n'), 'utf8');
console.log(`Generated ${entries.length} Faker locale loaders.`);
